CREATE DATABASE college;
USE college;
CREATE TABLE departments (dept_code VARCHAR(10) PRIMARY KEY, dept_name VARCHAR(50) NOT NULL);
CREATE TABLE students (roll_no INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(50) NOT NULL, email VARCHAR(80) UNIQUE, branch VARCHAR(10) DEFAULT 'CSE', marks DECIMAL(5,2), FOREIGN KEY (branch) REFERENCES departments(dept_code));
